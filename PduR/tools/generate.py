#!/usr/bin/env python3
"""Generate the demo profile's COM, PduR and CanIf configuration tables."""
import argparse
import json
from pathlib import Path
import re

def generate(config, output):
    signals = json.loads(config.read_text())["signals"]
    if not isinstance(signals, list) or not 1 <= len(signals) <= 16:
        raise ValueError("configure 1..16 signals")
    keys = ("signal_id", "com_tx", "com_rx", "canif_tx", "canif_rx", "can_id")
    for signal in signals:
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", signal["name"]):
            raise ValueError("invalid signal name")
        for key in keys:
            value = signal[key]
            if type(value) is not int or not 0 <= value <= (0x7ff if key == "can_id" else 0xffff):
                raise ValueError("invalid " + key)
    for key in (*keys, "name"):
        if len({s[key] for s in signals}) != len(signals):
            raise ValueError("duplicate " + key)
    parts = ['/* Generated by tools/generate.py; edit config/demo.json. */',
             '#include "Com.h"', '#include "PduR.h"', '#include "CanIf.h"']
    def table(ctype, name, fields):
        parts.append("static const " + ctype + " " + name + "[] = {")
        for s in signals:
            parts.append(" { " + ", ".join(str(s[k]) + "u" for k in fields) + " },")
        parts.append("};")
    table("Com_SignalType", "signals", ("signal_id", "com_tx", "com_rx"))
    table("PduR_RouteType", "txRoutes", ("com_tx", "canif_tx"))
    table("PduR_RouteType", "rxRoutes", ("canif_rx", "com_rx"))
    for name, key in (("txPdus", "canif_tx"), ("rxPdus", "canif_rx")):
        parts.append("static const CanIf_PduType " + name + "[] = {")
        parts.extend(" { %du, %du, 2u }," % (s[key], s["can_id"]) for s in signals)
        parts.append("};")
    n = len(signals)
    parts.extend([
        "const Com_ConfigType Com_Config = { signals, %du };" % n,
        "const PduR_ConfigType PduR_Config = { txRoutes, %du, rxRoutes, %du };" % (n, n),
        "const CanIf_ConfigType CanIf_Config = { txPdus, %du, rxPdus, %du };" % (n, n)])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(parts) + "\n")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        generate(args.config, args.output)
    except (ValueError, KeyError, TypeError) as exc:
        parser.exit(1, "configuration error: " + str(exc) + "\n")
